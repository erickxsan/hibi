export function translateToSpanish(value) {
  if (typeof value !== "string" || !value) return value;
  const direct = SPANISH_TRANSLATIONS[value];
  if (direct) return direct;
  for (const [pattern, replacement] of DYNAMIC_TRANSLATIONS) {
    const match = value.match(pattern);
    if (match) return replacement(match);
  }
  return value;
}

export function translateUiText(value, language) {
  return language === SUPPORTED_LANGUAGES.SPANISH ? translateToSpanish(value) : value;
}
